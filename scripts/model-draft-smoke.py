"""Make one real, consented model request using generated public synthetic data.

Run explicitly; ordinary CI does not download models or call external providers.
An optional key comes from GRAPHUNSLOPIFY_DRAFT_API_KEY, never a CLI argument.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

from graphunslopify.drafts import DraftPlan, DraftProvider, InvalidDraft
from graphunslopify.errors import SpecError
from graphunslopify.preview import PreviewState


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--endpoint", required=True)
    parser.add_argument("--model", required=True)
    parser.add_argument(
        "--protocol", choices=["chat", "responses"], default="responses"
    )
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    provider = DraftProvider(
        args.endpoint,
        args.model,
        args.protocol,
        os.environ.get("GRAPHUNSLOPIFY_DRAFT_API_KEY", ""),
    )
    content = b"epoch,score\n1,51\n2,54\n3,56\n4,59\n"
    record = {
        "recorded_at": datetime.now(timezone.utc).isoformat(),
        "provider": provider.public(),
        "python": platform.python_version(),
        "platform": platform.platform(),
        "source": "Public synthetic four-point training curve generated by this script",
        "source_data_sha256": hashlib.sha256(content).hexdigest(),
        "status": "not_started",
        "limits": "One integration example; not human usability, general model quality or speed evidence. No private observations or source paths transmitted.",
    }
    try:
        with tempfile.TemporaryDirectory(prefix="gu-model-smoke-") as folder:
            state = PreviewState(Path(folder), 1024 * 1024)
            data_info = state.upload("synthetic.csv", content)
            initial = {
                "kind": "line",
                "x": {"field": "score", "label": "Old horizontal axis"},
                "y": {"field": "epoch", "label": "Old vertical axis"},
                "output": {"stem": "figure", "formats": ["png", "svg", "pdf"]},
            }
            payload = {"spec": initial, "data_id": data_info["id"]}
            spec, data, _ = state.prepare(payload)
            request = DraftPlan(
                provider,
                data,
                spec,
                "Plot score against epoch as a line. Put epoch on the horizontal axis labeled Epoch and score on the vertical axis labeled Score. Set the figure title to Training progress. Keep the observed values unchanged. Do not add uncertainty or tests because sampling design is unspecified.",
            )
            disclosure = request.disclosure()
            record.update(
                {
                    "request_sha256": disclosure["request_sha256"],
                    "request_bytes": disclosure["request_bytes"],
                }
            )
            # Only synthetic task content; authorization headers are never serialized.
            (args.output / "disclosure.json").write_text(
                json.dumps(disclosure, indent=2) + "\n"
            )
            started = time.perf_counter()
            proposal = request.propose(consent=True)
            record["inference_seconds"] = time.perf_counter() - started
            (args.output / "proposal.json").write_text(
                json.dumps(proposal, indent=2) + "\n"
            )
            record.update(
                {
                    "request_sha256": proposal["request_sha256"],
                    "request_bytes": disclosure["request_bytes"],
                    "binding": proposal["binding"],
                    "applied_before_review": proposal["applied"],
                    "verified_before_render": proposal["verified"],
                }
            )
            candidate = proposal["spec"]
            if (
                candidate.get("kind"),
                candidate["x"]["field"],
                candidate["y"]["field"],
                candidate.get("title"),
            ) != ("line", "epoch", "score", "Training progress"):
                raise ValueError(
                    "The actual model proposal did not meet the requested source mapping/title"
                )
            if candidate.get("uncertainty") or candidate.get("significance"):
                raise ValueError(
                    "The actual model added unrequested statistical intent"
                )
            # This harness reviews the fixed synthetic task before explicitly rendering.
            rendered = state.render(
                {**payload, "spec": candidate, "client": "model-smoke", "generation": 1}
            )
            report = rendered["report"]
            if (
                not report
                or not report["ok"]
                or report["status"] != "passed"
                or rendered.get("export_errors")
            ):
                raise ValueError(
                    "The actual proposed figure did not pass strict rendering and exports"
                )
            if data["path"].read_bytes() != content:
                raise ValueError("The original input bytes changed")
            (args.output / "strict-report.json").write_text(
                json.dumps(report, indent=2) + "\n"
            )
            record.update(
                {
                    "status": "passed",
                    "strict_status": report["status"],
                    "original_data_unchanged": True,
                    "exports": [item["format"] for item in report["outputs"]],
                }
            )
    except (ValueError, OSError, TypeError, KeyError, SpecError) as error:
        record.update({"status": "failed", "error": str(error)})
        if isinstance(error, InvalidDraft):
            (args.output / "invalid-proposal.json").write_text(
                json.dumps(
                    {"envelope": error.envelope, "problems": error.problems}, indent=2
                )
                + "\n"
            )
        raise
    finally:
        (args.output / "checks.json").write_text(json.dumps(record, indent=2) + "\n")
    print(json.dumps(record, indent=2))


if __name__ == "__main__":
    main()
