/** Ship the same emitter in a wheel; users need no npm install or HTTP service. */
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { DIAGNOSTIC_ADVICE, UNKNOWN_DIAGNOSTIC } from "../src/diagnostics.ts";

// Parse plain canonical Python; translating figures still needs only Node.
execFileSync(process.env.PYTHON ?? (process.platform === "win32" ? "python" : "python3"), [
  "scripts/build-runtime-source.py", "--source", "python/graphunslopify/figure_runtime.py",
  "--out", "src/codegen/runtime-source.ts",
], { stdio: "inherit" });

// One implementation serves installed inspection and package-free generated plots.
const cellColour = readFileSync("python/graphunslopify/cell_colour.py", "utf8").replace(/\r\n/g, "\n");
writeFileSync("src/codegen/cell-colour-source.ts",
  "// Generated by npm run build:translator from python/graphunslopify/cell_colour.py.\n" +
  `export const CELL_COLOUR_SOURCE = ${JSON.stringify(cellColour)};\n`);
const workbook = readFileSync("python/graphunslopify/workbook.py", "utf8").replace(/\r\n/g, "\n");
writeFileSync("src/codegen/workbook-source.ts",
  "// Generated by npm run build:translator from python/graphunslopify/workbook.py.\n" +
  `export const WORKBOOK_SOURCE = ${JSON.stringify(workbook)};\n`);

await build({
  entryPoints: ["src/local.ts"],
  outfile: "python/graphunslopify/_translator.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  legalComments: "inline",
  banner: { js: "// Bundled from src/local.ts by npm run build:translator. Do not edit directly." },
});
copyFileSync("node_modules/zod/LICENSE", "python/graphunslopify/ZOD-LICENSE.txt");
copyFileSync("LICENSE", "python/LICENSE");
writeFileSync("python/graphunslopify/diagnostics.json",
  JSON.stringify({ advice: DIAGNOSTIC_ADVICE, unknown: UNKNOWN_DIAGNOSTIC }, null, 2) + "\n");
mkdirSync("python/graphunslopify/schemas", { recursive: true });
const environment = JSON.parse(readFileSync("docs/environment.schema.json", "utf8"));
const runtime = JSON.parse(readFileSync("docs/runtime-report.schema.json", "utf8"));
const { $schema, $id, ...environmentDefinition } = environment;
runtime.$defs = { ...runtime.$defs, environment: environmentDefinition };
runtime.properties.environment = { $ref: "#/$defs/environment" };
writeFileSync("docs/runtime-report.schema.json", JSON.stringify(runtime, null, 2) + "\n");
for (const name of ["manifest", "runtime-report", "audit-report", "environment", "comparison"]) {
  copyFileSync(`docs/${name}.schema.json`, `python/graphunslopify/schemas/${name}.schema.json`);
}

mkdirSync("python/graphunslopify/examples", { recursive: true });
copyFileSync("examples/quickstart.ipynb", "python/graphunslopify/examples/quickstart.ipynb");
